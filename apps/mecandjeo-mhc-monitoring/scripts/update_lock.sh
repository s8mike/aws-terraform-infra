#!/usr/bin/env bash
# Rebuilds requirements.lock: installs the packages listed in requirements.txt into a clean Python container and records
# the exact version of every package that ended up installed, including the ones those packages pull in themselves.
# The Docker build installs from requirements.lock, so every build gets exactly these versions.
#
# Usage, from apps/mecandjeo-mhc-monitoring:   bash scripts/update_lock.sh
# Then: review the change (git diff requirements.lock), rebuild the image, run the tests and the scans, and commit.
# Optional setting: PYTHON_IMAGE (default python:3.12-slim; keep it the same as the FROM line in the Dockerfile).
set -uo pipefail

PYTHON_IMAGE="${PYTHON_IMAGE:-python:3.12-slim}"
NEW_FILE="requirements.lock.new"

[ -f requirements.txt ] || { echo "requirements.txt not found: run this from apps/mecandjeo-mhc-monitoring" >&2; exit 2; }
docker info > /dev/null 2>&1 || { echo "Docker is not reachable: start Docker Desktop first" >&2; exit 2; }

echo "Installing the packages from requirements.txt into a clean $PYTHON_IMAGE container ..."

# The list goes in through standard input and only the result comes out, so no folders need to be shared with Docker.
# The result is written to a temporary file first: if anything fails, the existing lock file stays untouched.
if ! {
  echo "# Exact versions of every package in the container image. Generated by scripts/update_lock.sh: do not edit by hand."
  echo "# To change a package, edit requirements.txt and run: bash scripts/update_lock.sh"
  docker run --rm -i "$PYTHON_IMAGE" sh -c 'pip install -q --no-cache-dir -r /dev/stdin > /dev/null && pip freeze' < requirements.txt
} > "$NEW_FILE"; then
  rm -f "$NEW_FILE"
  echo "The install failed, so requirements.lock was NOT changed. Read the error above." >&2
  exit 1
fi

# Sanity check: the result must contain the main packages as exact versions (name==version).
for package in fastapi uvicorn SQLAlchemy alembic; do
  if ! grep -qiE "^${package}==" "$NEW_FILE"; then
    rm -f "$NEW_FILE"
    echo "The result did not contain $package==..., so requirements.lock was NOT changed." >&2
    exit 1
  fi
done

mv "$NEW_FILE" requirements.lock
echo "Wrote requirements.lock with $(grep -cE '^[A-Za-z0-9_.-]+==' requirements.lock) pinned packages."